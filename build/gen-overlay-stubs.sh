#!/bin/sh
# Generate dt/msm8998-google-walleye-overlay-stubs.dtsi (decision 2026-11-17-walleye-dtb-carries-overlay-symbols): one empty
# stub node, with its label, for every label the vendor dtbo overlay's __fixups__ names that OUR dtb (built with -@, WITHOUT the
# stubs) does not already define. With them, the bootloader's overlay merge finds every target it patches. Host only.
#
#   gen-overlay-stubs.sh DTBO_ENTRY OUR_DTB_AT OUT_DTSI
#     DTBO_ENTRY  the overlay entry the bootloader picks (androidboot.dtbo_idx=3): a dtb split out of dtbo.img
#     OUR_DTB_AT  our dtb compiled with -@ and without the stubs include (it has /__symbols__)
#     OUT_DTSI    the file written (labels sorted, so the output is the same on every run)
set -eu
OV=${1:?usage: gen-overlay-stubs.sh DTBO_ENTRY OUR_DTB_AT OUT_DTSI}
OUR=${2:?}
OUT=${3:?}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
fdtget -p "$OV" /__fixups__ | sort > "$T/need"
fdtget -p "$OUR" /__symbols__ | sort > "$T/have"
[ -s "$T/need" ] || { echo "gen-overlay-stubs: no __fixups__ in $OV" >&2; exit 1; }
[ -s "$T/have" ] || { echo "gen-overlay-stubs: $OUR has no /__symbols__ (build it with -@)" >&2; exit 1; }
comm -23 "$T/need" "$T/have" > "$T/missing"
{
  echo "// SPDX-License-Identifier: GPL-2.0-only OR BSD-2-Clause"
  echo "/*"
  echo " * GENERATED by build/gen-overlay-stubs.sh - do not edit. $(wc -l < "$T/missing") empty stub nodes, one per label the vendor dtbo"
  echo " * overlay (androidboot.dtbo_idx=3) targets that this board file does not define ($(wc -l < "$T/need") labels named, $(comm -12 "$T/need" "$T/have" | wc -l) ours)."
  echo " * The bootloader merges that overlay into the dtb it starts; the merge needs /__symbols__ and a node for every label."
  echo " * The kernel ignores them (no compatible); the container is status = \"disabled\" so the kernel's shared-gpio scan (gpiolib-shared) does not enter it and the vendor"
  echo " * nodes the overlay adds under a stub (synaptics_dsx@20 names pmi8998 gpio 2) do not claim a gpio of ours (research walleye-z20-tried-touch-gpio-leaf)."
  echo " * Decisions 2026-11-17-walleye-dtb-carries-overlay-symbols, 2026-11-19-walleye-stubs-disabled."
  echo " */"
  echo "/ {"
  echo "	vendor-overlay-stubs {"
  echo "		status = \"disabled\";"
  while IFS= read -r l; do echo "		$l: $l {};"; done < "$T/missing"
  echo "	};"
  echo "};"
} > "$OUT"
echo "gen-overlay-stubs: $(wc -l < "$T/missing") stubs -> $OUT"
